<h1><font size="5 px";>OVERVIEW</h1>
<p><font size="5 px";>Located in the heart of Nawanshahr City in the beautiful state of Punjab, India, Raja Hospital is a leading healthcare institution committed to providing exceptional medical care and services to the community. With 70 beds and a team of highly skilled medical professionals, we are dedicated to ensuring the well-being and recovery of our patients.

At Raja Hospital, we pride ourselves on being a NABH (National Accreditation Board for Hospitals & Healthcare Providers) certified hospital, which reflects our unwavering commitment to maintaining the highest standards of quality, safety, and patient care. This accreditation demonstrates our continuous efforts to provide excellence in healthcare services.

We understand the importance of state-of-the-art facilities in delivering accurate diagnoses and effective treatments. That’s why Raja Hospital is equipped with the best radiology labs in the region. Our advanced imaging technology enables our expert radiologists to provide precise and timely reports, aiding in the accurate diagnosis of various medical conditions.</p>

<h1><font size="5 px";>ABOUT OUR SPEICIALITIES</h1>
<p><font size="5 px";>As a trusted healthcare institution, Raja Hospital is renowned for its Trauma Centre, which provides round-the-clock emergency medical services. Our highly trained trauma team is skilled in handling critical situations and ensuring immediate and appropriate care for patients in need of urgent medical attention. We are dedicated to saving lives and providing comprehensive care during critical moments.

Raja Hospital is proud to have been the first hospital in the city to introduce modern healthcare machines, revolutionizing the medical landscape of Nawanshahr. Our commitment to innovation ensures that our patients have access to the latest medical advancements, enabling accurate diagnoses, effective treatments, and enhanced patient outcomes.</p>
 
